#!/usr/bin/env python3
"""Stub management for ShadowRunPrototype.cs.
  stubs.py list                  -> print all stub method signatures (name, params, line)
  stubs.py strip <file.cs>...    -> remove from ShadowRunPrototype.cs every stub whose
                                    (name, param-count) is implemented in the given partial files
  stubs.py progress              -> regenerate docs/remake-progress.md status table
"""
import re, sys, os, json, glob
ROOT = os.path.expanduser('~/Downloads/InfernoDrive-Unity')
MAIN = ROOT + '/Assets/Scripts/Assembly-CSharp/ShadowRunPrototype.cs'
SIG = re.compile(r'^\t((?:\[[^\]]+\]\s*)?(?:private|public|internal|protected)\s+(?:static\s+)?(?:async\s+)?(?:override\s+)?(?:[\w<>\[\],\.]+\s+))([A-Za-z_]\w*)\s*\((.*)\)\s*$')

def params_count(p):
    p = p.strip()
    if not p: return 0
    depth = 0; n = 1
    for ch in p:
        if ch in '<[(': depth += 1
        elif ch in '>])': depth -= 1
        elif ch == ',' and depth == 0: n += 1
    return n

def scan(path):
    """Return list of (name, nparams, start_line_idx, end_line_idx, sigline) for top-level (1-tab) methods."""
    lines = open(path, encoding='utf-8').read().split('\n')
    out = []
    i = 0
    while i < len(lines):
        m = SIG.match(lines[i])
        if m and i+1 < len(lines) and lines[i+1].rstrip() == '\t{':
            # find matching close at '\t}'
            j = i+2
            while j < len(lines) and lines[j] != '\t}':
                j += 1
            out.append((m.group(2), params_count(m.group(3)), i, j, lines[i]))
            i = j+1
        else:
            i += 1
    return lines, out

DEFAULT_VAL = r'(null|0f?|0\.0f|false|default|default\([^)]*\)|""|string\.Empty|Vector[234]\.zero|Color\.(white|black|clear)|Quaternion\.identity|Rect\.zero|new [\w<>\[\]\.]+\(\)|new [\w\.]+\[0\])'
def is_stub(lines, s, e):
    body = [l.strip() for l in lines[s+2:e] if l.strip()]
    if not body: return True
    for b in body:
        if re.match(r'^return ' + DEFAULT_VAL + r';$', b): continue
        if re.match(r'^\w+ = ' + DEFAULT_VAL + r';$', b): continue
        return False
    return True

def cmd_list():
    lines, ms = scan(MAIN)
    for name, n, s, e, sig in ms:
        print(('stub ' if is_stub(lines, s, e) else 'IMPL ') + f'{name}/{n}  L{s+1}  {sig.strip()}')

def cmd_strip(files):
    impl = set()
    for f in files:
        _, ms = scan(f)
        for name, n, *_ in ms:
            impl.add((name, n))
    lines, ms = scan(MAIN)
    removed = []
    for name, n, s, e, sig in reversed(ms):
        if (name, n) in impl and is_stub(lines, s, e):
            # remove lines s..e plus one following blank line if present
            end = e+1
            if end < len(lines) and lines[end].strip() == '': end += 1
            del lines[s:end]
            removed.append(f'{name}/{n}')
    open(MAIN, 'w', encoding='utf-8').write('\n'.join(lines))
    print('removed stubs:', len(removed))
    for r in reversed(removed): print('  ', r)

def cmd_progress():
    SP = os.path.dirname(os.path.abspath(__file__))
    idx = json.load(open(SP + '/methods.json'))
    cpp = {}
    for k, v in idx.items():
        if not k.startswith('ShadowRunPrototype_'): continue
        base = k[len('ShadowRunPrototype_'):k.rfind('_m')]
        cpp.setdefault(base, []).append((k, v))
    lines, ms = scan(MAIN)
    remaining = {(name, n) for name, n, s, e, sig in ms if is_stub(lines, s, e)}
    # implemented = all partial files
    impl = {}
    for f in sorted(glob.glob(ROOT + '/Assets/Scripts/Assembly-CSharp/ShadowRunPrototype*.cs')):
        L, M = scan(f)
        for name, n, s, e, sig in M:
            if not is_stub(L, s, e):
                impl[(name, n)] = os.path.basename(f)
    verified = set()
    vf = ROOT + '/docs/remake-verified.txt'
    if os.path.exists(vf):
        verified = {l.strip() for l in open(vf) if l.strip() and not l.startswith('#')}
    allm = sorted({(name, n) for name, n, *_ in scan(MAIN)[1]} | set(impl))
    rows = []
    counts = {'todo':0,'translated':0,'verified-in-play':0}
    for name, n in allm:
        key = f'{name}/{n}'
        if key in verified: st = 'verified-in-play'
        elif (name, n) in impl: st = 'translated'
        else: st = 'todo'
        counts[st] += 1
        cppnames = ', '.join(f'`{k}`' for k, v in cpp.get(name, []))
        rows.append(f'| `{key}` | {st} | {impl.get((name,n),"")} | {cppnames} |')
    out = ['# Remake progress — ShadowRunPrototype', '',
           f'Methods: {len(allm)} — todo {counts["todo"]}, translated {counts["translated"]}, verified-in-play {counts["verified-in-play"]}.', '',
           'Status is regenerated by `tools/remake/stubs.py progress`. `translated` = C# body written from the IL2CPP C++; ',
           '`verified-in-play` = behaviour checked in play mode against the shipped build (listed in `docs/remake-verified.txt`).', '',
           '| Method | Status | File | C++ function |', '|---|---|---|---|'] + rows
    os.makedirs(ROOT + '/docs', exist_ok=True)
    open(ROOT + '/docs/remake-progress.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(counts)

if __name__ == '__main__':
    c = sys.argv[1]
    if c == 'list': cmd_list()
    elif c == 'strip': cmd_strip(sys.argv[2:])
    elif c == 'progress': cmd_progress()
